/** Returns an array of `<label>[:<line>]: <message>` strings; empty when the manifest is valid. */
export function validateManifest(m, dirName, label) {
  const errs = []
  const err = (table, key, msg) => {
    const l = LINES.get(table)?.get(key)
    errs.push(`${label}${l ? `:${l}` : ''}: ${msg}`)
  }
  const q = (name, k) => (name ? `${name}.${k}` : k)
  const keys = (t, name, required, optional = []) => {
    for (const k of required) if (!Object.hasOwn(t, k)) err(t, '', `missing key ${q(name, k)}`)
    for (const k of Object.keys(t)) {
      if (!required.includes(k) && !optional.includes(k)) err(t, k, `unknown key ${q(name, k)}`)
    }
  }
  const sub = (t, k, name) => {
    if (!Object.hasOwn(t, k)) {
      err(t, '', `missing table [${q(name, k)}]`)
      return null
    }
    if (!isTable(t[k])) {
      err(t, k, `${q(name, k)} must be a table`)
      return null
    }
    return t[k]
  }
  const text = (t, k, name) => {
    const v = t[k]
    if (v === undefined) return // keys() already reported it missing
    if (typeof v !== 'string' || !v.trim() || CTRL_RE.test(v)) {
      err(t, k, `${q(name, k)} must be a non-empty single-line string`)
    }
  }
  const strArray = (t, k, name, { oneOf, unique = false, nonEmpty = false } = {}) => {
    const v = t[k]
    if (v === undefined) return
    if (!Array.isArray(v) || v.some((s) => typeof s !== 'string' || !s || CTRL_RE.test(s))) {
      err(t, k, `${q(name, k)} must be an array of non-empty single-line strings`)
      return
    }
    if (nonEmpty && v.length === 0) err(t, k, `${q(name, k)} must not be empty`)
    if (unique && new Set(v).size !== v.length) err(t, k, `${q(name, k)} must not repeat a value`)
    if (oneOf) for (const s of v) if (!oneOf.includes(s)) err(t, k, `${q(name, k)}: unknown value "${s}"`)
  }

  if (!isTable(m)) return [`${label}: manifest must be a table`]
  keys(m, '', ['mod', 'footprint', 'harnesses'])

  const mod = Object.hasOwn(m, 'mod') ? sub(m, 'mod', '') : null
  if (mod) {
    keys(mod, 'mod', ['id', 'name', 'description', 'version', 'reach_level', 'events'])
    if (typeof mod.id === 'string') {
      if (!ID_RE.test(mod.id)) err(mod, 'id', 'mod.id must be kebab-case (^[a-z0-9]+(-[a-z0-9]+)*$)')
      else if (mod.id !== dirName) err(mod, 'id', `mod.id "${mod.id}" must equal the directory name "${dirName}"`)
    } else if (mod.id !== undefined) err(mod, 'id', 'mod.id must be a string')
    text(mod, 'name', 'mod')
    text(mod, 'description', 'mod')
    if (mod.version !== undefined && !(typeof mod.version === 'string' && VERSION_RE.test(mod.version))) {
      err(mod, 'version', 'mod.version must match ^\\d+\\.\\d+\\.\\d+$')
    }
    if (mod.reach_level !== undefined && !(Number.isInteger(mod.reach_level) && mod.reach_level >= 0 && mod.reach_level <= 3)) {
      err(mod, 'reach_level', 'mod.reach_level must be an integer 0..3')
    }
    strArray(mod, 'events', 'mod', { oneOf: EVENTS, unique: true, nonEmpty: true })
  }

  const fp = Object.hasOwn(m, 'footprint') ? sub(m, 'footprint', '') : null
  if (fp) {
    const names = ['env_reads', 'file_writes', 'spawns', 'egress_hosts']
    keys(fp, 'footprint', names)
    for (const k of names) strArray(fp, k, 'footprint')
  }

  const hs = Object.hasOwn(m, 'harnesses') ? sub(m, 'harnesses', '') : null
  if (hs) {
    keys(hs, 'harnesses', HARNESSES)
    for (const h of HARNESSES) {
      if (!Object.hasOwn(hs, h)) continue
      const t = sub(hs, h, 'harnesses')
      if (!t) continue
      const name = `harnesses.${h}`
      if (typeof t.supported !== 'boolean') {
        err(t, Object.hasOwn(t, 'supported') ? 'supported' : '', `${name}.supported must be a boolean`)
        continue
      }
      if (!t.supported) {
        keys(t, name, ['supported', 'reason'])
        text(t, 'reason', name)
        continue
      }
      const claude = h === 'claude-code'
      keys(t, name, claude ? ['supported', 'events', 'surfaces'] : ['supported', 'events'], claude ? ['unsupported', 'degraded'] : ['requires', 'unsupported', 'degraded'])
      strArray(t, 'events', name, { oneOf: EVENTS, unique: true })
      if (claude) strArray(t, 'surfaces', name, { oneOf: SURFACES, unique: true })
      else strArray(t, 'requires', name)
      const allowed = claude ? [...EVENTS, ...SURFACES] : EVENTS
      for (const k of ['unsupported', 'degraded']) {
        if (!Object.hasOwn(t, k)) continue
        const st = sub(t, k, name)
        if (!st) continue
        for (const key of Object.keys(st)) {
          if (!allowed.includes(key)) err(st, key, `${name}.${k}.${key}: key must be one of ${allowed.join(', ')}`)
          else text(st, key, `${name}.${k}`)
        }
      }
    }
  }
  return errs
}

