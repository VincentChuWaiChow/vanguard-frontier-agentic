#!/usr/bin/env node
/**
 * Generator: the files marked "G" under mods/<id>/ plus catalog/mods.json.
 *
 * Source of truth is mods/<id>/mod.toml (plus patterns.json for the pattern mods) and the
 * two shared files scripts/mods/common.mjs and scripts/mods/runtime.mjs. Everything else
 * this script writes is derived and must never be hand-edited. Hand-written files in a mod
 * (README.md, bin/, hooks/register.ts, lib/core.mjs, ...) are never touched.
 *
 * mod.toml is read with a strict TOML-subset parser (comments, bare-key tables, basic
 * strings, integers, booleans, arrays of strings). Anything else is an error, so a manifest
 * can never mean one thing to this script and another to Python's tomllib.
 *
 * Deterministic by construction: no clock, no env, no network, no shell, nothing outside
 * the repo. Output is sorted; JSON is 2-space with a trailing newline.
 *
 * Usage:
 *   node scripts/generate-mods.mjs                    # write generated files, delete stale ones
 *   node scripts/generate-mods.mjs --check            # verify in sync (CI); writes nothing
 *   node scripts/generate-mods.mjs --print-manifests  # parsed mod.toml files as JSON
 *
 * Exports: parseToml, validateManifest, loadMods, renderMod, renderAll.
 *   loadMods(root) -> { mods, ctx, errors }   (the only function that reads the disk)
 *   renderAll(mods, ctx) -> Map<repo-relative path, content>, sorted by path
 */
import {
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  realpathSync,
  rmdirSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const HARNESSES = ['claude-code', 'kiro', 'codex']
const HARNESS_NAMES = { 'claude-code': 'Claude Code', kiro: 'Kiro', codex: 'Codex' }
const EVENTS = ['PreToolUse', 'PostToolUse', 'SessionStart'] // canonical order
const EV_KEBAB = { PreToolUse: 'pre-tool-use', PostToolUse: 'post-tool-use', SessionStart: 'session-start' }
const SURFACES = ['native', 'classic']
const FORBIDDEN_KEYS = new Set(['__proto__', 'constructor', 'prototype'])
const ID_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/
const VERSION_RE = /^\d+\.\d+\.\d+$/
const CTRL_RE = /[\u0000-\u001f\u007f]/
const LIVE_AGENT_RE = /-live-.*-guard-agent$/
const GEN_HEADER = '// Generated by scripts/generate-mods.mjs'

// Paths the generator owns inside a mod. Everything else in a mod is hand-written.
const OWNED_DIRS = ['.claude-plugin', 'claude-code', 'kiro', 'codex'] // every file inside is generated
const OWNED_FILES = {
  lib: ['common.mjs', 'runtime.mjs', 'patterns.mjs', 'live-agents.mjs'],
  hooks: ['hooks.json'],
}

const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0)
const json = (v) => JSON.stringify(v, null, 2) + '\n'
const isTable = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)

function aggregate(errors) {
  const e = new Error(errors.join('\n'))
  e.errors = errors
  return e
}

// ---------------------------------------------------------------------------------------
// TOML subset parser
// ---------------------------------------------------------------------------------------

// table object -> Map(key -> line); key '' is the table's own header line. Lets schema
// errors point at file:line without changing the plain-object shape parseToml returns.
const LINES = new WeakMap()
const ESCAPES = { '"': '"', '\\': '\\', n: '\n', t: '\t', r: '\r' }

export function parseToml(text, fileLabel = 'mod.toml') {
  const n = text.length
  const root = {}
  LINES.set(root, new Map())
  const defined = new Set() // explicitly declared [tables], by dotted path
  let cur = root
  let pos = 0
  let line = 1

  const fail = (msg = 'unsupported TOML', at = line) => {
    throw new Error(`${fileLabel}:${at}: ${msg}`)
  }
  const isWs = (c) => c === ' ' || c === '\t'
  const atNewline = () => text[pos] === '\n' || (text[pos] === '\r' && text[pos + 1] === '\n')
  const eatNewline = () => {
    pos += text[pos] === '\r' ? 2 : 1
    line++
  }
  const skipWs = () => {
    while (pos < n && isWs(text[pos])) pos++
  }
  const skipComment = () => {
    if (text[pos] === '#') while (pos < n && !atNewline()) pos++
  }
  const skipWsNl = () => {
    for (;;) {
      skipWs()
      if (pos < n && atNewline()) eatNewline()
      else if (text[pos] === '#') skipComment()
      else return
    }
  }
  const endOfLine = () => {
    skipWs()
    skipComment()
    if (pos >= n) return
    if (atNewline()) eatNewline()
    else fail()
  }

  const BARE = /[A-Za-z0-9_-]+/y
  const bareKey = () => {
    BARE.lastIndex = pos
    const m = BARE.exec(text)
    if (!m) return ''
    pos += m[0].length
    if (FORBIDDEN_KEYS.has(m[0])) fail(`forbidden key ${m[0]}`)
    return m[0]
  }

  const readString = () => {
    if (text.startsWith('"""', pos)) fail() // multiline basic string
    pos++
    let out = ''
    for (;;) {
      if (pos >= n) fail()
      const c = text[pos]
      if (c === '"') {
        pos++
        return out
      }
      if (c === '\\') {
        const e = text[pos + 1]
        if (e === 'u') {
          const hex = text.slice(pos + 2, pos + 6)
          if (!/^[0-9A-Fa-f]{4}$/.test(hex)) fail()
          const cp = parseInt(hex, 16)
          if (cp >= 0xd800 && cp <= 0xdfff) fail() // lone surrogate is not a scalar value
          out += String.fromCharCode(cp)
          pos += 6
        } else if (e !== undefined && Object.hasOwn(ESCAPES, e)) {
          out += ESCAPES[e]
          pos += 2
        } else fail()
        continue
      }
      const code = c.charCodeAt(0)
      if (code === 0x0a || code === 0x0d || (code < 0x20 && c !== '\t') || code === 0x7f) fail()
      out += c
      pos++
    }
  }

  const readArray = () => {
    const startLine = line
    pos++
    const items = []
    for (;;) {
      skipWsNl()
      if (pos >= n) fail('unsupported TOML', startLine)
      if (text[pos] === ']') {
        pos++
        return items
      }
      if (text[pos] !== '"') fail() // only strings: no nesting, no mixed arrays, no inline tables
      items.push(readString())
      skipWsNl()
      if (text[pos] === ',') pos++
      else if (text[pos] === ']') {
        pos++
        return items
      } else fail()
    }
  }

  const SCALAR = /(?:-?(?:0|[1-9][0-9]*)|true|false)(?=[ \t\r\n#,\]]|$)/y
  const readValue = () => {
    const c = text[pos]
    if (c === '"') return readString()
    if (c === '[') return readArray()
    SCALAR.lastIndex = pos
    const m = SCALAR.exec(text)
    if (!m) fail() // literal strings, floats, dates, inline tables, ...
    pos += m[0].length
    if (m[0] === 'true') return true
    if (m[0] === 'false') return false
    const v = Number(m[0])
    if (!Number.isSafeInteger(v)) fail()
    return v || 0 // folds -0 into 0
  }

  while (pos < n) {
    skipWs()
    if (pos >= n) break
    if (atNewline()) {
      eatNewline()
      continue
    }
    if (text[pos] === '#') {
      skipComment()
      continue
    }
    if (text[pos] === '[') {
      if (text[pos + 1] === '[') fail() // array of tables
      const headerLine = line
      pos++
      const segs = []
      for (;;) {
        skipWs()
        const seg = bareKey()
        if (!seg) fail()
        segs.push(seg)
        skipWs()
        if (text[pos] === '.') pos++
        else if (text[pos] === ']') {
          pos++
          break
        } else fail()
      }
      endOfLine()
      cur = root
      for (const seg of segs) {
        if (!Object.hasOwn(cur, seg)) {
          const t = {}
          LINES.set(t, new Map())
          cur[seg] = t
          LINES.get(cur).set(seg, headerLine)
        } else if (!isTable(cur[seg])) fail(`duplicate key ${seg}`, headerLine)
        cur = cur[seg]
      }
      const dotted = segs.join('.')
      if (defined.has(dotted)) fail(`duplicate table [${dotted}]`, headerLine)
      defined.add(dotted)
      LINES.get(cur).set('', headerLine)
      continue
    }
    const keyLine = line
    const key = bareKey() // quoted keys fall through to fail() below
    if (!key) fail()
    skipWs()
    if (text[pos] !== '=') fail() // also rejects dotted keys
    pos++
    skipWs()
    const value = readValue()
    endOfLine()
    if (Object.hasOwn(cur, key)) fail(`duplicate key ${key}`, keyLine)
    cur[key] = value
    LINES.get(cur).set(key, keyLine)
  }
  return root
}

