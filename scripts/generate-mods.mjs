// CLI
// ---------------------------------------------------------------------------------------

export function main(argv = process.argv.slice(2), root = ROOT) {
  const modes = ['--check', '--print-manifests']
  if (argv.length > 1 || (argv.length === 1 && !modes.includes(argv[0]))) {
    console.error('Usage: node scripts/generate-mods.mjs [--check | --print-manifests]')
    return 2
  }
  const fail = (errors) => {
    for (const e of errors) console.error(e)
    return 1
  }

  if (argv[0] === '--print-manifests') {
    const { entries, errors } = readManifests(root)
    if (errors.length) return fail(errors)
    console.log(JSON.stringify(Object.fromEntries(entries.map((e) => [e.dir, e.manifest])), null, 2))
    return 0
  }

  const { mods, ctx, errors } = loadMods(root)
  let expected = new Map()
  if (ctx.common !== null && ctx.runtime !== null) {
    try {
      expected = renderAll(mods, ctx)
    } catch (e) {
      errors.push(...(e.errors ?? [e.message]))
    }
  }
  if (errors.length) return fail(errors)

  let drift, stale
  try {
    drift = findDrift(root, expected)
    stale = findStale(root, mods.map((m) => m.id), expected)
  } catch (e) {
    return fail([e.message])
  }

  if (argv[0] === '--check') {
    const paths = [...new Set([...drift, ...stale])].sort(cmp)
    if (paths.length === 0) {
      console.log('OK: mods in sync')
      return 0
    }
    console.error(`FAIL: mods out of sync (${paths.length} paths). Run: npm run mods:write`)
    for (const p of paths) console.error(`  ${p}`)
    return 1
  }

  try {
    const realRoot = realpathSync(root)
    for (const rel of drift) safeWrite(root, realRoot, rel, expected.get(rel))
    for (const rel of stale) unlinkSync(path.join(root, rel))
    for (const m of mods) for (const d of OWNED_DIRS) pruneEmpty(path.join(root, 'mods', m.id, d))
  } catch (e) {
    return fail([e.message])
  }
  console.log(`Generated ${mods.length} mods for ${HARNESSES.length} harnesses`)
  return 0
}

function isEntryPoint() {
  if (!process.argv[1]) return false
  try {
    return import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href
  } catch {
    return false
  }
}

if (isEntryPoint()) process.exitCode = main()
