// Check components without following symlinks, before any read, mkdir or removal.
function safePath(root, rel) {
  const base = path.resolve(root)
  const abs = path.resolve(base, rel)
  const relative = path.relative(base, abs)
  if (relative === '..' || relative.startsWith('..' + path.sep) || path.isAbsolute(relative)) {
    throw new Error(`${rel}: escapes the repo`)
  }
  let current = base
  for (const part of relative.split(path.sep).filter(Boolean)) {
    current = path.join(current, part)
    try {
      if (lstatSync(current).isSymbolicLink()) throw new Error(`${rel}: symlink in repo path`)
    } catch (e) {
      if (e.code === 'ENOENT') break
      throw e
    }
  }
  return abs
}

function readText(root, rel) {
  const buf = readFileSync(safePath(root, rel))
  const s = buf.toString('utf8')
  if (!Buffer.from(s, 'utf8').equals(buf)) throw new Error('not valid UTF-8, so it cannot be copied byte for byte')
  return s
}

function modDirs(root, errors) {
  try {
    return readdirSync(safePath(root, 'mods'), { withFileTypes: true })
      .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
      .map((e) => e.name)
      .sort(cmp)
  } catch (e) {
    errors.push(e.code === 'ENOENT' ? 'mods/: directory is missing' : e.message)
    return []
  }
}

/** Parse (no schema check) every mods/<dir>/mod.toml. */
function readManifests(root) {
  const errors = []
  const entries = []
  for (const dir of modDirs(root, errors)) {
    const label = `mods/${dir}/mod.toml`
    try {
      entries.push({ dir, label, manifest: parseToml(readText(root, label), label) })
    } catch (e) {
      errors.push(e.code === 'ENOENT' ? `${label}: missing` : e.message.startsWith(label) ? e.message : `${label}: ${e.message}`)
    }
  }
  return { entries, errors }
}

const usesLiveAgents = (patterns) => Array.isArray(patterns) && patterns.some((p) => Array.isArray(p?.agents))

/**
 * Read and validate every mod. Mods with errors are left out of `mods`; every error is
 * collected rather than thrown. `ctx` carries the shared inputs renderMod needs:
 * { common, runtime, agentIds } (agentIds is null unless a mod needs the live-agent lists).
 */
export function loadMods(root = ROOT) {
  const { entries, errors } = readManifests(root)
  const mods = []
  for (const { dir, label, manifest } of entries) {
    let ok = true
    const report = (msgs) => {
      errors.push(...msgs)
      if (msgs.length) ok = false
    }
    report(validateManifest(manifest, dir, label))
    let patterns = null
    const pLabel = `mods/${dir}/patterns.json`
    try {
      const p = JSON.parse(readText(root, pLabel))
      if (!Array.isArray(p) || p.some((e) => !isTable(e))) throw new Error('must be an array of objects')
      for (const e of p) {
        if (Object.hasOwn(e, 'agents') && !(Array.isArray(e.agents) && e.agents.every((a) => typeof a === 'string'))) {
          throw new Error(`pattern ${e.id}: agents must be an array of strings`)
        }
      }
      patterns = p
    } catch (e) {
      if (e.code !== 'ENOENT') report([`${pLabel}: ${e.message}`])
    }
    if (ok) mods.push({ id: dir, dir: `mods/${dir}`, manifest, patterns })
  }

  const ctx = { common: null, runtime: null, agentIds: null }
  for (const k of ['common', 'runtime']) {
    const rel = `scripts/mods/${k}.mjs`
    try {
      ctx[k] = readText(root, rel)
    } catch (e) {
      errors.push(`${rel}: ${e.code === 'ENOENT' ? 'missing' : e.message}`)
    }
  }
  if (mods.some((m) => usesLiveAgents(m.patterns))) {
    try {
      const agents = JSON.parse(readText(root, 'catalog/agents.json'))
      if (!Array.isArray(agents)) throw new Error('must be an array')
      ctx.agentIds = agents.map((a) => a?.id).filter((id) => typeof id === 'string')
    } catch (e) {
      errors.push(`catalog/agents.json: ${e.code === 'ENOENT' ? 'missing' : e.message}`)
    }
  }
  return { mods, ctx, errors }
}

// ---------------------------------------------------------------------------------------
// Rendering (pure)
// ---------------------------------------------------------------------------------------

const inCanonicalOrder = (events) => EVENTS.filter((e) => events.includes(e))

function hookEntry(command) {
  return [{ hooks: [{ type: 'command', command }] }]
}

function hooksByEvent(events, command) {
  return { hooks: Object.fromEntries(inCanonicalOrder(events).map((e) => [e, hookEntry(command(e))])) }
}

function renderUnsupported(manifest, h) {
  const t = manifest.harnesses[h]
  const unsupported = t.unsupported ?? {}
  const degraded = t.degraded ?? {}
  if (t.supported && !Object.keys(unsupported).length && !Object.keys(degraded).length) return null
  const blocks = [
    `# ${manifest.mod.name} on ${HARNESS_NAMES[h]}`,
    '<!-- Generated by scripts/generate-mods.mjs from mod.toml. Do not edit. -->',
  ]
  if (!t.supported) blocks.push(`## Not supported\n\n${t.reason}`)
  for (const [title, table] of [['Unsupported', unsupported], ['Degraded', degraded]]) {
    const ks = Object.keys(table).sort(cmp)
    if (ks.length) blocks.push(`## ${title}\n\n${ks.map((k) => `- \`${k}\`: ${table[k]}`).join('\n')}`)
  }
  return blocks.join('\n\n') + '\n'
}

/** Every generated file of one mod: Map<repo-relative path, content>. */
export function renderMod(mod, ctx) {
  if (typeof ctx?.common !== 'string' || typeof ctx?.runtime !== 'string') {
    throw new TypeError('renderMod: ctx.common and ctx.runtime must be strings (see loadMods)')
  }
  const { id, manifest: m, patterns } = mod
  const out = new Map()
  const put = (rel, content) => out.set(`mods/${id}/${rel}`, content)

  put('lib/common.mjs', ctx.common)
  put('lib/runtime.mjs', ctx.runtime)

  if (patterns) {
    put('lib/patterns.mjs', `${GEN_HEADER} from patterns.json. Do not edit.\nexport default ${JSON.stringify(patterns, null, 2)};\n`)
  }
  if (usesLiveAgents(patterns)) {
    if (!Array.isArray(ctx.agentIds)) throw new TypeError('renderMod: ctx.agentIds is required for a mod with agent-bearing patterns')
    const selected = [...new Set(ctx.agentIds.filter((a) => LIVE_AGENT_RE.test(a)))].sort(cmp)
    const known = new Set(selected)
    const covered = new Set()
    const errors = []
    for (const p of patterns) {
      for (const a of Array.isArray(p.agents) ? p.agents : []) {
        if (known.has(a)) covered.add(a)
        else errors.push(`mods/${id}/patterns.json: pattern ${p.id} references "${a}", which is not a live guard agent in catalog/agents.json`)
      }
    }
    if (errors.length) throw aggregate(errors)
    const coveredList = [...covered].sort(cmp)
    const uncovered = selected.filter((a) => !covered.has(a))
    put(
      'lib/live-agents.mjs',
      `${GEN_HEADER} from patterns.json and catalog/agents.json. Do not edit.\n` +
        `export const covered = ${JSON.stringify(coveredList, null, 2)};\n` +
        `export const uncovered = ${JSON.stringify(uncovered, null, 2)};\n`,
    )
  }

  const cc = m.harnesses['claude-code']
  if (cc.supported && cc.surfaces.includes('native')) {
    put('.claude-plugin/plugin.json', json({ name: id, version: m.mod.version, description: m.mod.description }))
    put('hooks/hooks.json', json({ modules: ['./register.ts'] }))
  }
  if (cc.supported && cc.surfaces.includes('classic')) {
    put(
      'claude-code/settings.hooks.json',
      json(hooksByEvent(cc.events, (e) => `node "$CLAUDE_PROJECT_DIR/.claude/vanguard-mods/${id}/bin/hook.mjs" --harness claude-code --event ${e}`)),
    )
  }
  if (m.harnesses.kiro.supported) {
    for (const e of inCanonicalOrder(m.harnesses.kiro.events)) {
      put(
        `kiro/${id}-${EV_KEBAB[e]}-hook.json`,
        json({
          version: 'v1',
          hooks: [
            {
              name: `${id}:${e}`,
              description: m.mod.description,
              trigger: e,
              action: { type: 'command', command: `node .kiro/vanguard-mods/${id}/bin/hook.mjs --harness kiro --event ${e}` },
            },
          ],
        }),
      )
    }
  }
  if (m.harnesses.codex.supported) {
    put('codex/hooks.json', json(hooksByEvent(m.harnesses.codex.events, (e) => `node .codex/vanguard-mods/${id}/bin/hook.mjs --harness codex --event ${e}`)))
  }
  for (const h of HARNESSES) {
    const md = renderUnsupported(m, h)
    if (md) put(`${h}/UNSUPPORTED.md`, md)
  }
  return new Map([...out].sort((a, b) => cmp(a[0], b[0])))
}

/** Every generated file for all mods plus catalog/mods.json, sorted by path; input order is irrelevant. */
export function renderAll(mods, ctx) {
  const sorted = [...mods].sort((a, b) => cmp(a.id, b.id))
  const files = new Map()
  const errors = []
  for (const mod of sorted) {
    try {
      for (const [k, v] of renderMod(mod, ctx)) files.set(k, v)
    } catch (e) {
      errors.push(...(e.errors ?? [e.message]))
    }
  }
  if (errors.length) throw aggregate(errors)
  files.set(
    'catalog/mods.json',
    json(
      sorted.map(({ id, manifest: m }) => ({
        id,
        name: m.mod.name,
        version: m.mod.version,
        description: m.mod.description,
        reach_level: m.mod.reach_level,
        events: [...m.mod.events],
        harnesses: HARNESSES.filter((h) => m.harnesses[h].supported).sort(cmp),
        path: `mods/${id}`,
      })),
    ),
  )
  return new Map([...files].sort((a, b) => cmp(a[0], b[0])))
}

// ---------------------------------------------------------------------------------------
// Disk sync
// ---------------------------------------------------------------------------------------

const exists = (abs) => {
  try {
    lstatSync(abs)
    return true
  } catch {
    return false
  }
}

function walkFiles(root, rel, found = []) {
  const abs = safePath(root, rel)
  let entries
  try {
    entries = readdirSync(abs, { withFileTypes: true })
  } catch {
    return found
  }
  for (const e of entries) {
    const child = `${rel}/${e.name}`
    safePath(root, child)
    if (e.isDirectory()) walkFiles(root, child, found)
    else found.push(child) // files, symlinks and anything else count as files
  }
  return found
}

/** Generated paths on disk that the current render no longer produces. */
function findStale(root, ids, expected) {
  const stale = []
  for (const id of ids) {
    const base = `mods/${id}`
    for (const d of OWNED_DIRS) stale.push(...walkFiles(root, `${base}/${d}`))
    for (const [d, names] of Object.entries(OWNED_FILES)) {
      for (const name of names) if (exists(safePath(root, `${base}/${d}/${name}`))) stale.push(`${base}/${d}/${name}`)
    }
  }
  return stale.filter((rel) => !expected.has(rel)).sort(cmp)
}

function findDrift(root, expected) {
  const drift = []
  for (const [rel, content] of expected) {
    const abs = safePath(root, rel)
    let actual = null
    try {
      actual = readFileSync(abs)
    } catch {
      // missing or unreadable counts as drift
    }
    if (!actual || !actual.equals(Buffer.from(content, 'utf8'))) drift.push(rel)
  }
  return drift
}

function safeWrite(root, realRoot, rel, content) {
  const abs = safePath(root, rel)
  mkdirSync(path.dirname(abs), { recursive: true })
  const dir = realpathSync(path.dirname(abs))
  if (dir !== realRoot && !dir.startsWith(realRoot + path.sep)) throw new Error(`${rel}: resolves outside the repo`)
  if (exists(abs) && lstatSync(abs).isSymbolicLink()) throw new Error(`${rel}: is a symlink; refusing to write through it`)
  writeFileSync(abs, content)
}

function pruneEmpty(abs) {
  let entries
  try {
    entries = readdirSync(abs, { withFileTypes: true })
  } catch {
    return
  }
  for (const e of entries) if (e.isDirectory()) pruneEmpty(path.join(abs, e.name))
  if (readdirSync(abs).length === 0) rmdirSync(abs)
}

