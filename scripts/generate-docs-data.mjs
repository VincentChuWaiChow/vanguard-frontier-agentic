#!/usr/bin/env node
/**
 * Generate docs/_data/catalog.yml from the live catalog.
 *
 * Single source of truth for all counts displayed on the Jekyll documentation site.
 * Run this after any catalog change to keep docs in sync.
 *
 * Usage: node scripts/generate-docs-data.mjs
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// Load catalog data
const agents = JSON.parse(readFileSync(join(root, 'catalog/agents.json'), 'utf8'));
const skills = JSON.parse(readFileSync(join(root, 'catalog/skills.json'), 'utf8'));
const mcpRefs = JSON.parse(readFileSync(join(root, 'catalog/mcp-references.json'), 'utf8'));
const rules = JSON.parse(readFileSync(join(root, 'catalog/rules.json'), 'utf8'));
const roles = JSON.parse(readFileSync(join(root, 'catalog/install-roles.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
// Workflow catalog is additive: a checkout without any workflow reports zero rather
// than failing the docs build, matching how the TUI loader treats a missing file.
let workflows = [];
try {
  workflows = JSON.parse(readFileSync(join(root, 'catalog/workflows.json'), 'utf8')).workflows || [];
} catch {
  workflows = [];
}

// Compute counts
const providers = [...new Set(agents.map(a => a.provider))].sort();
const validateScripts = Object.keys(pkg.scripts || {}).filter(k => k.startsWith('validate:'));
const agentDirs = readdirSync(join(root, 'agents'));
const skillDirs = readdirSync(join(root, 'skills'));
const roleIds = Object.keys(roles.roles).sort();

// Count maestro routing scenarios from the test output or fixture
let maestroScenarios = 357; // default
try {
  const maestroFixture = readFileSync(join(root, 'tests/fixtures/maestro-routing-scenarios.json'), 'utf8');
  const scenarios = JSON.parse(maestroFixture);
  maestroScenarios = Array.isArray(scenarios) ? scenarios.length : 357;
} catch {
  // Use default if fixture doesn't exist
}

// Generate YAML
// Compute provider taxonomy (categorize providers for documentation)
const providerCounts = {};
for (const agent of agents) {
  providerCounts[agent.provider] = (providerCounts[agent.provider] || 0) + 1;
}

const taxonomy = [
  { category: 'Cloud Hyperscalers', providers: ['aws', 'azure', 'gcp', 'oci', 'alibaba', 'huawei'] },
  { category: 'European Cloud', providers: ['ovhcloud', 'ionos', 'scaleway', 'hetzner', 'contabo'] },
  { category: 'Container & Orchestration', providers: ['kubernetes', 'argocd', 'fluxcd', 'istio', 'cilium'] },
  { category: 'Security & Supply Chain', providers: ['falco', 'kyverno', 'sigstore', 'cert-manager'] },
  { category: 'Observability', providers: ['opentelemetry', 'prometheus'] },
  { category: 'Infrastructure as Code', providers: ['terraform'] },
  { category: 'AI & Compute', providers: ['nvidia'] },
  { category: 'Frontend & Web', providers: ['frontend'] },
  { category: 'Developer Platforms', providers: ['backstage', 'dotnet', 'java', 'kotlin', 'php', 'python', 'typescript', 'generic', 'multi-cloud'] },
  { category: 'ERP & Finance', providers: ['netsuite', 'accounting', 'finance', 'sap'] },
  { category: 'Business Functions', providers: ['salesforce', 'legal', 'hr', 'marketing'] },
  { category: 'Work Management & Collaboration', providers: ['atlassian'] },
  { category: 'Microsoft 365 & Dynamics 365', providers: ['microsoft'] },
  { category: 'Data & Analytics Platforms', providers: ['databricks', 'snowflake'] },
];

const taxonomyYaml = taxonomy.map(t => {
  const entries = t.providers
    .filter(p => providerCounts[p] > 0)
    .map(p => `      - name: "${p}"\n        agents: ${providerCounts[p]}`)
    .join('\n');
  return `  - category: "${t.category}"\n    providers:\n${entries}`;
}).join('\n');

const yaml = `# Auto-generated by scripts/generate-docs-data.mjs
# Do NOT edit manually — run: node scripts/generate-docs-data.mjs
# This file is the single source of truth for all catalog counts in Jekyll docs.

agents: ${agents.length}
skills: ${skills.length}
providers: ${providers.length}
mcp_references: ${mcpRefs.length}
rules: ${rules.length}
workflows: ${workflows.length}
install_roles: ${roleIds.length}
validation_gates: ${validateScripts.length}
agent_directories: ${agentDirs.length}
skill_directories: ${skillDirs.length}
maestro_scenarios: ${maestroScenarios}
version: "${pkg.version}"

# Provider list (flat)
provider_list:
${providers.map(p => `  - "${p}"`).join('\n')}

# Provider taxonomy (grouped by category with agent counts)
provider_taxonomy:
${taxonomyYaml}

# Workflow list (delegation workflows in .claude/workflows/)
workflow_list:
${workflows.length ? workflows.map(w => `  - name: "${w.name}"\n    phases: ${(w.phases || []).length}`).join('\n') : '  []'}

# Role list
role_list:
${roleIds.map(r => `  - "${r}"`).join('\n')}

# Harness list
harness_list:
  - "claude-code"
  - "codex"
  - "copilot"
  - "cursor"
  - "gemini"
  - "kiro"
`;

// Write output
const outDir = join(root, 'docs/_data');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'catalog.yml');
writeFileSync(outPath, yaml);

console.log(`OK: wrote ${outPath}`);
console.log(`  agents=${agents.length} skills=${skills.length} providers=${providers.length} roles=${roleIds.length} gates=${validateScripts.length}`);

